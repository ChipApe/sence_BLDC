#include "foc_kernel/include/mc.h"

mcSys_t Motor1;

void SystemInit(void);
int main(void);

/*******************************************************************************
 函数名称：    int main(void)
 功能描述：    主程序入口
 输入参数：    无
 返 回 值：    无
 其它说明：
 修改日期      版本号          修改人            修改内容
 -----------------------------------------------------------------------------
 2026/1/30    V1.0           ChipApe            创建
 *******************************************************************************/
int main(void)
{
		__disable_irq();	// 关中断
    Hardware_Init();	// 硬件初始化
    Sys_Init(&Motor1);				// 软件初始化
    __enable_irq();		// 开中断

    for (;;)
    {
        __NOP();
        __NOP();
        __NOP();
        __NOP();
    }
}

/*******************************************************************************
 函数名称：    void SystemInit(void)
 功能描述：    初始化时钟，上电后在MAIN函数之前运行
 输入参数：    无
 返 回 值：    无
 其它说明：
 修改日期      版本号          修改人            修改内容
 -----------------------------------------------------------------------------
 2026/1/30    V1.0           ChipApe            创建
 *******************************************************************************/
void SystemInit(void)
{
    SYS_WR_PROTECT = 0x7a83;	// 解除系统寄存器写保护

    SYS_AFE_REG0 |= BIT15;    // BIT15:PLLPDN
    SYS_CLK_CFG = 0x000001ff; // BIT8:0: CLK_HS,1:PLL  | BIT[7:0]CLK_DIV  | 1ff对应96M时钟

    FLASH_CFG |= 0x00080000;	// enable prefetch
    SYS_WR_PROTECT = 0;				// 解除系统寄存器写保护
}
